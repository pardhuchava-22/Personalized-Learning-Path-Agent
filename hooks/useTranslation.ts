export const getSavedLocale = (): string => {
  const saved = typeof window !== 'undefined' ? (localStorage.getItem('user_language_pref') || 'English') : 'English';
  if (saved.startsWith('Español') || saved.startsWith('Spanish')) return 'es';
  if (saved.startsWith('Français') || saved.startsWith('French')) return 'fr';
  if (saved.startsWith('Deutsch') || saved.startsWith('German')) return 'de';
  if (saved.startsWith('हिन्दी') || saved.startsWith('Hindi')) return 'hi';
  if (saved.startsWith('తెలుగు') || saved.startsWith('Telugu')) return 'te';
  if (saved.startsWith('日本語') || saved.startsWith('Japanese')) return 'ja';
  if (saved.startsWith('中文') || saved.startsWith('Chinese') || saved.startsWith('Mandarin')) return 'zh';
  if (saved.startsWith('العربية') || saved.startsWith('Arabic')) return 'ar';
  return 'en';
};

export function useTranslation() {
  const [locale, setLocale] = useState<string>(getSavedLocale);

  useEffect(() => {
    const handleLangChange = () => {
      setLocale(getSavedLocale());
    };
    window.addEventListener('languagechange', handleLangChange);
    window.addEventListener('storage', handleLangChange);
    return () => {
      window.removeEventListener('languagechange', handleLangChange);
      window.removeEventListener('storage', handleLangChange);
    };
  }, []);

  const t = useCallback((key: string): string => {
    const locDict = localizedTranslations[locale];
    if (locDict && locDict[key]) return locDict[key];
    return translations[key] || key;
  }, [locale]);

  return { t, locale, setLocale };
}
